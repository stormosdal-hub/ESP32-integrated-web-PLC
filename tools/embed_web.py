#!/usr/bin/env python3
"""Pack the web IDE into a C source file for the firmware.

    python tools/embed_web.py <web_dir> <out.c>

Every file under <web_dir> is gzip-compressed (served with
Content-Encoding: gzip) and listed in `web_assets[]` with its URL path and
MIME type. `web_assets_etag` is a hash of the whole UI, so browsers revalidate
cheaply and pick up a new UI right after a firmware update.
"""
import gzip
import hashlib
import os
import sys

MIME = {
    '.html': 'text/html; charset=utf-8',
    '.js': 'application/javascript; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.json': 'application/json; charset=utf-8',
    '.svg': 'image/svg+xml',
    '.png': 'image/png',
    '.ico': 'image/x-icon',
    '.txt': 'text/plain; charset=utf-8',
}


def main(src, out):
    files = []
    for root, dirs, names in os.walk(src):
        dirs[:] = sorted(d for d in dirs if not d.startswith('.'))
        for n in sorted(names):
            if n.startswith('.'):
                continue
            full = os.path.join(root, n)
            rel = '/' + os.path.relpath(full, src).replace(os.sep, '/')
            files.append((rel, full))
    if not files:
        sys.exit('embed_web: no files in %s' % src)

    digest = hashlib.sha1()
    body = ['/* Generated by tools/embed_web.py from web/ - do not edit. */',
            '#include "web_assets.h"', '']
    table = []
    raw_total = gz_total = 0
    for i, (rel, full) in enumerate(files):
        with open(full, 'rb') as f:
            data = f.read()
        digest.update(rel.encode('utf-8'))
        digest.update(data)
        gz = gzip.compress(data, compresslevel=9, mtime=0)
        raw_total += len(data)
        gz_total += len(gz)
        body.append('static const uint8_t a%d[%d] = {' % (i, len(gz)))
        for k in range(0, len(gz), 24):
            body.append('  ' + ','.join(str(b) for b in gz[k:k + 24]) + ',')
        body.append('};')
        mime = MIME.get(os.path.splitext(rel)[1].lower(), 'application/octet-stream')
        table.append('  {"%s", "%s", a%d, %d},' % (rel, mime, i, len(gz)))

    body.append('')
    body.append('const web_asset_t web_assets[] = {')
    body.extend(table)
    body.append('};')
    body.append('const size_t web_assets_count = %d;' % len(files))
    body.append('const char web_assets_etag[] = "\\"%s\\"";' % digest.hexdigest()[:16])
    body.append('')

    text = '\n'.join(body)
    # only touch the output when it changes (keeps incremental builds quiet)
    try:
        with open(out, 'r', encoding='utf-8') as f:
            if f.read() == text:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('embed_web: %d files, %d KB -> %d KB gzip' % (len(files), raw_total // 1024, gz_total // 1024))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
